-- Apply once to an existing project. Do not rerun supabase_schema.sql:
-- that file drops and recreates the application tables.

ALTER TABLE orders DROP CONSTRAINT IF EXISTS orders_status_check;

UPDATE orders
SET status = CASE status
  WHEN 'preparing' THEN 'pending'
  WHEN 'ready' THEN 'ready to pick up'
  WHEN 'completed' THEN 'picked up'
  WHEN 'cancelled' THEN 'canceled'
  ELSE status
END
WHERE status IN ('preparing', 'ready', 'completed', 'cancelled');

ALTER TABLE orders
  ADD CONSTRAINT orders_status_check
  CHECK (status IN ('pending', 'ready to pick up', 'picked up', 'canceled'));

CREATE TABLE IF NOT EXISTS customer_order_history (
  history_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id      integer NOT NULL UNIQUE,
  customer_id   integer NOT NULL,
  customer_name varchar(100) NOT NULL,
  order_type    varchar(20) NOT NULL,
  order_status  varchar(30) NOT NULL,
  outcome       varchar(20) NOT NULL CHECK (outcome IN ('successful', 'canceled')),
  notes         varchar(255),
  placed_at     timestamptz NOT NULL,
  finalized_at  timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  total_amount  numeric(10,2) NOT NULL DEFAULT 0,
  items         jsonb NOT NULL DEFAULT '[]'::jsonb
);
CREATE INDEX IF NOT EXISTS idx_customer_order_history_customer
  ON customer_order_history (customer_id, placed_at DESC);

CREATE OR REPLACE FUNCTION save_finalized_order_history()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  target_order orders%ROWTYPE;
  target_customer_name varchar(100);
  target_outcome varchar(20);
  target_items jsonb;
  target_total numeric(10,2);
BEGIN
  IF TG_OP = 'DELETE' THEN
    target_order := OLD;
  ELSE
    target_order := NEW;
  END IF;

  IF target_order.status NOT IN ('picked up', 'canceled') THEN
    IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
    RETURN NEW;
  END IF;

  target_outcome := CASE WHEN target_order.status = 'picked up' THEN 'successful' ELSE 'canceled' END;
  SELECT full_name INTO target_customer_name
  FROM users WHERE user_id = target_order.customer_id;

  SELECT
    COALESCE(jsonb_agg(jsonb_build_object(
      'product_id', oi.product_id,
      'name', p.name,
      'image', p.image,
      'quantity', oi.quantity,
      'unit_price', oi.unit_price
    ) ORDER BY oi.order_item_id), '[]'::jsonb),
    COALESCE(SUM(oi.quantity * oi.unit_price), 0)
  INTO target_items, target_total
  FROM order_items oi
  LEFT JOIN products p ON p.product_id = oi.product_id
  WHERE oi.order_id = target_order.order_id;

  INSERT INTO customer_order_history (
    order_id, customer_id, customer_name, order_type, order_status,
    outcome, notes, placed_at, finalized_at, total_amount, items
  ) VALUES (
    target_order.order_id, target_order.customer_id, COALESCE(target_customer_name, 'Customer'),
    target_order.order_type, target_order.status, target_outcome, target_order.notes,
    target_order.created_at, CURRENT_TIMESTAMP, target_total, target_items
  )
  ON CONFLICT (order_id) DO UPDATE SET
    customer_id = EXCLUDED.customer_id,
    customer_name = EXCLUDED.customer_name,
    order_type = EXCLUDED.order_type,
    order_status = EXCLUDED.order_status,
    outcome = EXCLUDED.outcome,
    notes = EXCLUDED.notes,
    placed_at = EXCLUDED.placed_at,
    finalized_at = EXCLUDED.finalized_at,
    total_amount = EXCLUDED.total_amount,
    items = EXCLUDED.items;

  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS orders_save_finalized_history ON orders;
CREATE TRIGGER orders_save_finalized_history
AFTER UPDATE OF status ON orders
FOR EACH ROW
WHEN (NEW.status IN ('picked up', 'canceled'))
EXECUTE FUNCTION save_finalized_order_history();

DROP TRIGGER IF EXISTS orders_preserve_finalized_history ON orders;
CREATE TRIGGER orders_preserve_finalized_history
BEFORE DELETE ON orders
FOR EACH ROW
WHEN (OLD.status IN ('picked up', 'canceled'))
EXECUTE FUNCTION save_finalized_order_history();

-- Preserve final orders that existed before this migration.
DO $$
DECLARE
  finalized_order record;
BEGIN
  FOR finalized_order IN
    SELECT order_id FROM orders WHERE status IN ('picked up', 'canceled')
  LOOP
    UPDATE orders SET status = status WHERE order_id = finalized_order.order_id;
  END LOOP;
END;
$$;

-- Create orders and price/lock available products in one database transaction.
CREATE OR REPLACE FUNCTION create_order_for_customer(
  p_customer_id integer,
  p_order_type varchar,
  p_notes varchar,
  p_items jsonb
)
RETURNS TABLE(order_id integer, total_amount numeric)
LANGUAGE plpgsql
AS $$
DECLARE
  customer_is_active boolean;
  entry jsonb;
  item_product_id integer;
  item_quantity integer;
  item_product_numeric numeric;
  item_quantity_numeric numeric;
  item_price numeric(8,2);
  created_order_id integer;
  order_total numeric(10,2) := 0;
  item_count integer;
  seen_product_ids integer[] := ARRAY[]::integer[];
BEGIN
  IF p_order_type IS NULL OR p_order_type NOT IN ('dine-in', 'take-out', 'delivery')
     OR length(COALESCE(p_notes, '')) > 255
     OR jsonb_typeof(p_items) IS DISTINCT FROM 'array' THEN
    RAISE EXCEPTION 'Invalid order details.';
  END IF;

  SELECT role = 'customer' AND status = 'active'
  INTO customer_is_active
  FROM users
  WHERE users.user_id = p_customer_id;
  IF customer_is_active IS DISTINCT FROM TRUE THEN
    RAISE EXCEPTION 'Active customer not found.';
  END IF;

  item_count := jsonb_array_length(p_items);
  IF item_count < 1 OR item_count > 50 THEN
    RAISE EXCEPTION 'Order must contain between 1 and 50 items.';
  END IF;

  FOR entry IN SELECT jsonb_array_elements(p_items)
  LOOP
    IF jsonb_typeof(entry) <> 'object'
       OR COALESCE(entry->>'product_id', '') !~ '^[0-9]+$'
       OR COALESCE(entry->>'quantity', '') !~ '^[0-9]+$' THEN
      RAISE EXCEPTION 'Order items are invalid.';
    END IF;
    item_product_numeric := (entry->>'product_id')::numeric;
    item_quantity_numeric := (entry->>'quantity')::numeric;
    IF item_product_numeric < 1 OR item_product_numeric > 2147483647
       OR item_product_numeric <> trunc(item_product_numeric)
       OR item_quantity_numeric < 1 OR item_quantity_numeric > 99
       OR item_quantity_numeric <> trunc(item_quantity_numeric) THEN
      RAISE EXCEPTION 'Order item quantity or product is invalid.';
    END IF;
    item_product_id := item_product_numeric::integer;
    IF item_product_id = ANY(seen_product_ids) THEN
      RAISE EXCEPTION 'Order items are duplicated.';
    END IF;
    seen_product_ids := array_append(seen_product_ids, item_product_id);
  END LOOP;

  INSERT INTO orders (customer_id, order_type, status, notes)
  VALUES (p_customer_id, p_order_type, 'pending', NULLIF(BTRIM(p_notes), ''))
  RETURNING orders.order_id INTO created_order_id;

  FOR entry IN SELECT jsonb_array_elements(p_items)
  LOOP
    item_product_id := (entry->>'product_id')::integer;
    item_quantity := (entry->>'quantity')::integer;

    SELECT price INTO item_price
    FROM products
    WHERE product_id = item_product_id
      AND is_available = 1
      AND is_archived = 0
    FOR SHARE;
    IF NOT FOUND THEN
      RAISE EXCEPTION 'A menu item is unavailable.';
    END IF;

    INSERT INTO order_items (order_id, product_id, quantity, unit_price)
    VALUES (created_order_id, item_product_id, item_quantity, item_price);
    order_total := order_total + item_quantity * item_price;
  END LOOP;

  RETURN QUERY SELECT created_order_id, order_total;
END;
$$;

REVOKE ALL ON FUNCTION create_order_for_customer(integer, varchar, varchar, jsonb) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION create_order_for_customer(integer, varchar, varchar, jsonb) TO service_role;
